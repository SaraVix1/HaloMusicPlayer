/// An icon glyph at `size` logical pixels (Lucide's 24px grid scaled).
pub fn icon<'a>(icon: Icon, size: f32) -> Text<'a> {
    text(icon.codepoint().to_string())
        .font(FONT)
        .size(size)
        .line_height(1.0)
        .shaping(text::Shaping::Basic)
}
